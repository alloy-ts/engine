import { Transpiler } from "../core/transpiler";
import { run, ShellError, CapabilityError } from "../core/shell";
import { runBuildPipeline } from "./build_pipeline";
import { join, basename, extname, resolve, dirname } from "node:path";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";

export interface CompileOptions {
  /** Disable alloy:web sidecar — smaller binary, no WebKit dependency. */
  web?: boolean;
  /** Build type: "release" | "debug". Default: "release" */
  buildType?: "release" | "debug";
}

// ── Step 1: Transpile TS → ES5 ────────────────────────────────────────────

async function transpileInput(inputPath: string): Promise<string> {
  let source = await Bun.file(inputPath).text();

  const ctx = {
    filename: inputPath,
    debug: false,
    target: "desktop" as const
  };

  // Run build-time pipeline (Stage 2 + 3)
  source = await runBuildPipeline(source, ctx);

  const loader =
    inputPath.endsWith(".tsx") ? "tsx" :
    inputPath.endsWith(".jsx") ? "jsx" :
    inputPath.endsWith(".ts")  ? "ts"  : "js";
  return new Transpiler(loader).transformSync(source);
}

// ── Step 2: Embed ES5 as C string literal header ──────────────────────────

function embedAsHeader(es5: string): string {
  const escaped = es5
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, '\\n"\n"');
  return `/* Auto-generated by alloy compile — do not edit */\n"${escaped}"\n`;
}

// ── Public API ────────────────────────────────────────────────────────────

export async function compile(
  input: string,
  outdir: string,
  opts: CompileOptions = {},
): Promise<void> {
  const inputPath  = resolve(input);
  const outputDir  = resolve(outdir);
  const buildType  = opts.buildType ?? "release";
  const enableWeb  = opts.web ?? true;
  const scriptName = basename(inputPath, extname(inputPath));
  const binaryName = scriptName + (process.platform === "win32" ? ".exe" : "");

  if (!existsSync(inputPath)) {
    throw new Error(`input file not found: ${input}`);
  }

  mkdirSync(outputDir, { recursive: true });

  // ── 1. Transpile ──────────────────────────────────────────────────────
  console.log(`[alloy:compile] transpiling ${input}…`);
  const es5 = await transpileInput(inputPath);

  // ── 2. Write build artefacts ──────────────────────────────────────────
  const buildDir   = join(tmpdir(), `alloy_build_${scriptName}`);
  const cmakeBuild = join(buildDir, "cmake_build");
  mkdirSync(cmakeBuild, { recursive: true });

  // Embedded script header
  const headerPath = join(buildDir, "user_script_embed.h");
  writeFileSync(headerPath, embedAsHeader(es5), "utf8");

  // Embedded alloyconfig.toml — bakes noWebAPI into the binary so the
  // C host reads it at startup without needing an external config file.
  // When --no-web is passed, both the compile-time flag (ALLOY_ENABLE_WEB=OFF)
  // and the runtime flag (noWebAPI=true) are set for belt-and-suspenders.
  const configPath = join(buildDir, "alloyconfig.toml");
  writeFileSync(
    configPath,
    `# Auto-generated by alloy compile\nnoWebAPI = ${!enableWeb}\n`,
    "utf8",
  );

  console.log(`[alloy:compile] build dir → ${buildDir}`);

  // ── 3. Locate AlloyScript source root ─────────────────────────────────
  const alloyRoot = dirname(dirname(dirname(import.meta.path)));
  if (!existsSync(join(alloyRoot, "CMakeLists.txt"))) {
    throw new Error(`AlloyScript source root not found at ${alloyRoot}`);
  }

  const cpuCount       = String(navigator.hardwareConcurrency ?? 4);
  const cmakeBuildType = buildType === "release" ? "Release" : "Debug";

  try {
    // ── 4. cmake configure ─────────────────────────────────────────────
    // All arguments are escaped by the Alloy shell tag.
    // cmake is in the ALLOWED_EXECUTABLES capability whitelist.
    console.log("[alloy:compile] cmake configure…");
    await run`cmake ${alloyRoot}
      -B ${cmakeBuild}
      -DCMAKE_BUILD_TYPE=${cmakeBuildType}
      -DALLOY_ENABLE_WEB=${enableWeb ? "ON" : "OFF"}
      -DALLOY_USER_SCRIPT_HEADER=${headerPath}
      -DCMAKE_RUNTIME_OUTPUT_DIRECTORY=${outputDir}`;

    // ── 5. cmake build ─────────────────────────────────────────────────
    console.log("[alloy:compile] cmake build…");
    await run`cmake --build ${cmakeBuild} --target alloy_host -j ${cpuCount}`;

  } catch (err: unknown) {
    if (err instanceof CapabilityError) {
      console.error(`[alloy:compile] capability denied: ${(err as CapabilityError).message}`);
      process.exit(1);
    }
    if (err instanceof ShellError) {
      console.error(`[alloy:compile] build failed:\n${(err as ShellError).result.stderr.trim()}`);
      process.exit(1);
    }
    throw err;
  }

  const binaryPath = join(outputDir, binaryName);
  console.log(
    existsSync(binaryPath)
      ? `[alloy:compile] ✓ ${binaryPath}`
      : `[alloy:compile] ✓ build complete → ${outputDir}`,
  );
}
